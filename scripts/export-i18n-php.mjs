import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { messages } from "../src/i18n/messages.ts";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const outDir = resolve(root, "php/lang");
mkdirSync(outDir, { recursive: true });

const quote = (value) => `'${String(value).replace(/\\/g, "\\\\").replace(/'/g, "\\'")}'`;

for (const [locale, dictionary] of Object.entries(messages)) {
  const rows = Object.entries(dictionary).map(([key, value]) => `    ${quote(key)} => ${quote(value)},`);
  const body = `<?php\n// Generated by scripts/export-i18n-php.mjs from src/i18n/messages.ts\nreturn [\n${rows.join("\n")}\n];\n`;
  writeFileSync(resolve(outDir, `${locale}.php`), body, "utf8");
  console.log(`${locale}: ${rows.length} keys`);
}
