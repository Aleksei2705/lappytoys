function fromCourse(course: Course): CoursePageCopy {
  return {
    badge: course.badge,
    duration: course.duration,
    level: course.level,
    intro: course.intro,
    details: course.details,
    learn: course.learn,
    forWhom: course.forWhom,
  };
}

export function getCoursePageCopy(id: string, locale: Locale): CoursePageCopy | null {
  const course = getCourseById(id);
  if (!course) return null;
  if (locale === "kk" && kk[id]) return kk[id];
  return fromCourse(course);
}
